from unittest.mock import patch

SCRIPTS = Path(__file__).resolve().parents[1] / 'skills/quorum/scripts'
sys.path.insert(0, str(SCRIPTS))
from quorum_test_support import QUEUE_HELP
SID = '11111111-1111-4111-8111-111111111111'
MID = '22222222-2222-4222-8222-222222222222'
CONVERSATION = '66666666-6666-4666-8666-666666666666'
# Generated by cmd-shim 7.0.0, the writer npm uses, for a global npm install of the package.
NPM_SHIM = '\r\n'.join((
    '@ECHO off', 'GOTO start', ':find_dp0', 'SET dp0=%~dp0', 'EXIT /b', ':start', 'SETLOCAL', 'CALL :find_dp0', '',
    'IF EXIST "%dp0%\\node.exe" (', '  SET "_prog=%dp0%\\node.exe"', ') ELSE (', '  SET "_prog=node"',
    '  SET PATHEXT=%PATHEXT:;.JS;=;%', ')', '',
    'endLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & "%_prog%"  '
    '"%dp0%\\node_modules\\@openai\\codex\\bin\\codex.js" %*', ''))
# Answers `queue --help` with the recorded 0.166.0 text, and records any other argv. A queue send prints the
# recorded success line for its thread, as the real CLI does.
RECORDER = '\n'.join((
    "const fs = require('fs'), argv = process.argv.slice(2);",
    "if (argv[argv.length - 1] === '--help') {",
    "  process.stdout.write(fs.readFileSync(process.env.QUORUM_SHIM_HELP));",
    "} else {",
    "  fs.writeFileSync(process.env.QUORUM_SHIM_CAPTURE, JSON.stringify(argv));",
    "  const thread = argv.indexOf('--thread');",
    "  if (thread >= 0) process.stdout.write('Queued message 01a1b23b-83f8-74e1-b1df-91544014a099 for thread ' +",
    "                                       argv[thread + 1] + '.\\n');",
    "}", ''))


def install(root, shim=NPM_SHIM):
    (root / 'codex.cmd').write_bytes(shim.encode())
    script = root / 'node_modules/@openai/codex/bin/codex.js'
    script.parent.mkdir(parents=True)
    script.write_text(RECORDER)
    return root / 'codex.cmd', script


def record(root):
    return {'engine':'codex', 'session_ref':SID, 'agent_id':'agent', 'quorum_id':'q', 'quorum':'team',
            'project_ref':'shared', 'cwd':str(root), 'role':'test'}


def message(role='peer'):
    return {'id':MID, 'recipient_id':'agent', 'sender_id':'peer-agent', 'sender_role':role, 'reply_to':None,
            'priority':'normal', 'conversation_id':CONVERSATION, 'sequence':3, 'body':'peer text'}


class Harness(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='qshim-')
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()


class ShimResolutionTests(Harness):
    def test_an_npm_shim_runs_its_entry_point_under_its_bundled_node(self):
        from quorum_session import shim_command
        shim, script = install(self.root)
        node = self.root / 'node.exe'
        node.touch()
        self.assertEqual(shim_command(str(shim)), [str(node), str(script)])

    def test_without_a_bundled_node_the_entry_point_uses_node_from_path(self):
        from quorum_session import shim_command
        shim, script = install(self.root)
        with patch('quorum_session.shutil.which', return_value='C:\\node\\node.exe'):
            self.assertEqual(shim_command(str(shim)), ['C:\\node\\node.exe', str(script)])

    def test_anything_but_a_batch_shim_is_run_as_it_is(self):
        from quorum_session import shim_command
        self.assertEqual(shim_command('C:\\codex\\codex.exe'), ['C:\\codex\\codex.exe'])

    def test_every_shim_that_cannot_be_bypassed_is_refused(self):
        from quorum_session import shim_command
        missing = NPM_SHIM.replace('codex.js', 'other.js')
        for name, shim, node in (('foreign', '@echo off\r\ncodex.exe %*\r\n', 'C:\\node\\node.exe'),
                                 ('no entry point', missing, 'C:\\node\\node.exe'),
                                 ('no node', NPM_SHIM, None),
                                 ('node is a shim too', NPM_SHIM, 'C:\\node\\node.cmd')):
            with self.subTest(name), tempfile.TemporaryDirectory(prefix='qshim-') as folder:
                path, _ = install(Path(folder), shim)
                with patch('quorum_session.shutil.which', return_value=node), self.assertRaises(ValueError):
                    shim_command(str(path))

    def test_a_shim_that_cannot_be_bypassed_is_unsent_and_starts_no_child(self):
        from quorum_claude_pipe import DeliveryUnsent
        from quorum_session import enqueue
        shim, _ = install(self.root, '@echo off\r\ncodex.exe %*\r\n')
        with patch('quorum_session.shutil.which', return_value=str(shim)), \
             patch('quorum_claude_pipe.subprocess.Popen', side_effect=AssertionError('must not spawn')), \
             self.assertRaises(DeliveryUnsent):
            enqueue(record(self.root), message(), self.root)


@unittest.skipUnless(os.name == 'nt', 'needs cmd.exe and a real batch shim')
class RealShimTests(Harness):
    def setUp(self):
        super().setUp()
        self.shim, _ = install(self.root)
        self.capture = self.root / 'argv.json'
        self.marker = self.root / 'injected.txt'
        (self.root / 'help.txt').write_bytes(QUEUE_HELP)
        environment = patch.dict(os.environ, {'QUORUM_SHIM_CAPTURE':str(self.capture),
                                              'QUORUM_SHIM_HELP':str(self.root / 'help.txt')})
        environment.start()
        self.addCleanup(environment.stop)

    def received(self):
        return json.loads(self.capture.read_text(encoding='utf-8'))

    def delivered(self, role):
        """Run the real delivery path once; returns what enqueue sent and what the target received."""
        import quorum_session
        sent = []
        real = quorum_session.run_child
        locate = shutil.which
        def spy(command, **options):
            sent.append(command)
            return real(command, **options)
        with patch('quorum_session.shutil.which',
                   side_effect=lambda name: str(self.shim) if name == 'codex' else locate(name)), \
             patch('quorum_session.run_child', side_effect=spy):
            quorum_session.enqueue(record(self.root), message(role), self.root)
        # The contract's help read runs through the same bypass, never cmd.exe; the send is the other child.
        probes = [command for command in sent if command[-2:] == ['queue', '--help']]
        sends = [command for command in sent if command not in probes]
        self.assertEqual([command[0] for command in probes], [sends[0][0]])
        self.assertEqual(len(sends), 1)
        return sends[0], self.received()

    def test_the_shim_itself_cuts_an_argument_at_the_first_newline(self):
        # The defect this route exists to avoid; if npm's shim ever stops doing this, say so here.
        subprocess.run([str(self.shim), 'queue', '--message', 'line1\nline2\nline3'], check=True, timeout=30)
        self.assertEqual(self.received(), ['queue', '--message', 'line1'])

    def test_the_whole_multiline_prompt_reaches_the_target(self):
        command, received = self.delivered('peer')
        prompt = command[-1]
        self.assertGreater(prompt.count('\n'), 3)
        self.assertEqual(received, ['queue', '--thread', SID, '--message', prompt])
        self.assertIn('"--conversation-id"', received[-1])

    def test_percent_and_quote_handling_survive_and_nothing_is_executed(self):
        hostile = 'x" & echo pwned>"' + str(self.marker) + '" & "%PATH%^|<>!%~dp0%*'
        command, received = self.delivered(hostile)
        self.assertEqual(received, ['queue', '--thread', SID, '--message', command[-1]])
        self.assertIn('%PATH%', received[-1])
        self.assertFalse(self.marker.exists())
