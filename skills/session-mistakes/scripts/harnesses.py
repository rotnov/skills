"""Session-history adapters: one per harness, all yielding the same record.

To add a harness, subclass `Adapter`, implement `discover` and `parse`, and
append an instance to `ADAPTERS`. Nothing else in the tool depends on a
harness by name. Standard library only.
"""

from __future__ import annotations

import io
import json
import re
import shutil
import subprocess
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Iterator
from urllib.parse import unquote

# Message kinds. Only HUMAN messages are ever labeled.
HUMAN = "human"  # typed (or dictated) by the person
ASSISTANT = "assistant"  # agent prose
INJECTED = "injected"  # system reminders, environment and instruction context
TOOL = "tool"  # tool results
AUTOMATED = "automated"  # hooks, schedules, heartbeats, CI and task notifications
AGENT = "agent"  # another agent: subagent briefs and reports, peer messages
COMMAND = "command"  # slash commands and local shell commands, without prose
INTERRUPT = "interrupt"  # the person stopped the agent; no text

# Bump when parsing or classification changes: `collect` then re-reads every file.
VERSION = 2
MAX_LINE = 8_000_000  # skip pathological lines (inline images, tool dumps)
MAX_TEXT = 20_000


@dataclass(frozen=True)
class Record:
    harness: str
    session_id: str
    project: str
    timestamp: str
    turn_index: int  # 0-based index of the human turn this record belongs to
    role: str  # "user" or "assistant"
    kind: str
    text: str
    model: str = ""


@dataclass(frozen=True)
class Source:
    harness: str
    path: Path  # the transcript file; its size and mtime drive incremental runs


_BLOCK_TAGS = (
    "system-reminder",
    "system_reminder",
    "environment_context",
    "in-app-browser-context",
    "external_browser_tabs",
    "codex_internal_context",
    "user_info",
    "local-command-caveat",
    "preview-annotation-context",
    "recommended_plugins",
    "user_instructions",
    "rules",
    "skill",
    "image",
)
_BLOCK_RE = re.compile(
    r"<(" + "|".join(re.escape(tag) for tag in _BLOCK_TAGS) + r")\b[^>]*>.*?</\1>", re.S
)
_OPEN_TAG_RE = re.compile(r"\s*<([A-Za-z][\w:-]*)")
_AUTOMATED_TAGS = {
    "task-notification",
    "scheduled-task",
    "ci-monitor-event",
    "heartbeat",
    "local-command-stdout",
    "local-command-stderr",
    "bash-stdout",
    "bash-stderr",
    "send_user_message_question_reply",
    "external_codex_apps_open_page",
    "external_codex_apps_selected_page_part_1_of_1",
    "turn_aborted",
    "side-sessions-event",
    "user_action",
}
_AGENT_TAGS = {"cross-session-message", "subagent_notification", "codex_delegation"}
_COMMAND_TAGS = {"command-name", "command-message", "bash-input", "user_shell_command"}
_COMMAND_ARGS_RE = re.compile(r"<command-args>(.*?)</command-args>", re.S)
_AGENT_PREFIX_RE = re.compile(
    r"\s*(\[Quorum\b|\[agent-bridge\]|\[Subagent hand-back\]|\[Agent message\b"
    r"|This session is being continued from a previous conversation"
    r"|\[Your previous response had no visible output)",
)
_INJECTED_PREFIX_RE = re.compile(
    r"\s*(# AGENTS\.md instructions for |\[Image[: ]|# Files mentioned by the user:"
    r"|Caveat: The messages below were generated by the user while running)"
)
_AUTOMATED_PREFIX_RE = re.compile(r"\s*Automation: ")
_VOICE_RE = re.compile(r"<realtime_delegation>.*?<input>(.*?)</input>", re.S)
_IDE_CONTEXT_RE = re.compile(r"\s*# Context from my IDE setup:.*?## My request for Codex:\s*", re.S)
_INTERRUPT_RE = re.compile(r"\s*\[Request interrupted by user")
_USER_QUERY_RE = re.compile(r"<user_query>(.*?)</user_query>", re.S)


def classify_user_text(text: str) -> tuple[str, str]:
    """Return (kind, cleaned text) for one user-role message body.

    Works on text alone, so every adapter can use it as the last line of
    defence after its own structured signals.
    """
    if _INTERRUPT_RE.match(text):
        return INTERRUPT, ""
    queries = _USER_QUERY_RE.findall(text)
    if queries:
        text = "\n".join(queries)
    spoken = _VOICE_RE.findall(text)
    if spoken:  # a voice front end relaying what the person said
        text = "\n".join(spoken)
    text = _IDE_CONTEXT_RE.sub("", _BLOCK_RE.sub("", text), count=1).strip()
    if not text:
        return INJECTED, ""
    if _AGENT_PREFIX_RE.match(text):
        return AGENT, ""
    if _AUTOMATED_PREFIX_RE.match(text):
        return AUTOMATED, ""
    if _INJECTED_PREFIX_RE.match(text):
        return INJECTED, ""
    tag = _OPEN_TAG_RE.match(text)
    if tag:
        name = tag.group(1)
        if name in _AUTOMATED_TAGS:
            return AUTOMATED, ""
        if name in _AGENT_TAGS:
            return AGENT, ""
        if name in _COMMAND_TAGS:
            args = " ".join(a.strip() for a in _COMMAND_ARGS_RE.findall(text)).strip()
            # A slash command with prose arguments carries a real request.
            return (HUMAN, args) if len(args.split()) >= 3 else (COMMAND, "")
    return HUMAN, text[:MAX_TEXT]


@contextmanager
def open_text(path: Path) -> Iterator[Iterable[str]]:
    """Open a transcript as text lines; `.zst` files stream through `zstd`.

    Yields an empty iterable when the file cannot be read.
    """
    if path.suffix == ".zst":
        zstd = shutil.which("zstd")
        if not zstd:
            yield ()
            return
        process = subprocess.Popen(
            [zstd, "-dc", "--", str(path)], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL
        )
        try:
            yield io.TextIOWrapper(process.stdout, encoding="utf-8", errors="replace")
        finally:
            process.stdout.close()
            process.kill()
            process.wait()
        return
    try:
        handle = path.open("r", encoding="utf-8", errors="replace")
    except OSError:
        yield ()
        return
    with handle:
        yield handle


def _lines(path: Path) -> Iterator[dict]:
    with open_text(path) as handle:
        for line in handle:
            if len(line) > MAX_LINE:
                continue
            try:
                value = json.loads(line)
            except ValueError:
                continue
            if isinstance(value, dict):
                yield value


def _text_blocks(content: object, block_types: tuple[str, ...] = ("text",)) -> str:
    if isinstance(content, str):
        return content
    parts = []
    for block in content if isinstance(content, list) else []:
        if isinstance(block, dict) and block.get("type") in block_types:
            parts.append(str(block.get("text", "")))
    return "\n".join(part for part in parts if part)


class Adapter:
    name = ""

    def discover(self, home: Path) -> Iterable[Source]:
        raise NotImplementedError

    def parse(self, source: Source) -> Iterator[Record]:
        raise NotImplementedError

    def excluded(self, home: Path) -> dict[str, int]:
        """Counts of transcript files this adapter deliberately leaves out."""
        return {}


class _Turns:
    """Tracks the human-turn index while an adapter walks one session."""

    def __init__(self) -> None:
        self.index = -1

    def of(self, kind: str) -> int:
        if kind == HUMAN:
            self.index += 1
        return max(self.index, 0)


class ClaudeCode(Adapter):
    """`<home>/.claude/projects/<encoded cwd>/<session id>.jsonl`.

    Subagent transcripts (`<session id>/subagents/`) hold agent-to-agent
    traffic only and are not read.
    """

    name = "claude"

    def discover(self, home: Path) -> Iterable[Source]:
        for path in sorted((home / ".claude" / "projects").glob("*/*.jsonl")):
            yield Source(self.name, path)

    def excluded(self, home: Path) -> dict[str, int]:
        root = home / ".claude" / "projects"
        return {"subagent transcripts": sum(1 for _ in root.glob("*/*/subagents/*.jsonl"))}

    def parse(self, source: Source) -> Iterator[Record]:
        turns = _Turns()
        project = ""
        for row in _lines(source.path):
            kind_of_row = row.get("type")
            if kind_of_row not in ("user", "assistant") or row.get("isSidechain"):
                continue
            project = project or str(row.get("cwd") or "")
            message = row.get("message") if isinstance(row.get("message"), dict) else {}
            content = message.get("content")
            base = dict(
                harness=self.name,
                session_id=source.path.stem,
                project=project,
                timestamp=str(row.get("timestamp") or ""),
            )
            if kind_of_row == "assistant":
                text = _text_blocks(content)
                if text.strip():
                    yield Record(
                        **base,
                        turn_index=turns.of(ASSISTANT),
                        role="assistant",
                        kind=ASSISTANT,
                        text=text[:MAX_TEXT],
                        model=str(message.get("model") or ""),
                    )
                continue
            kind, text = self._user_kind(row, content)
            yield Record(**base, turn_index=turns.of(kind), role="user", kind=kind, text=text)

    def _user_kind(self, row: dict, content: object) -> tuple[str, str]:
        if "toolUseResult" in row or (
            isinstance(content, list)
            and any(isinstance(b, dict) and b.get("type") == "tool_result" for b in content)
        ):
            return TOOL, ""
        origin = row.get("origin") if isinstance(row.get("origin"), dict) else {}
        origin_kind = origin.get("kind")
        if origin_kind == "task-notification":
            return AUTOMATED, ""
        if origin_kind and origin_kind != "human":
            return AGENT, ""  # peer sessions, subagent hand-backs, channels
        if row.get("isCompactSummary") or row.get("isMeta"):
            return INJECTED, ""
        if str(row.get("entrypoint") or "").startswith("sdk"):
            return AGENT, ""  # started by a program, not a person
        return classify_user_text(_text_blocks(content))


class Codex(Adapter):
    """`<home>/.codex/sessions/<YYYY>/<MM>/<DD>/rollout-*.jsonl` and the flat
    `<home>/.codex/archived_sessions/` folder; older files in both are
    zstd-compressed (`.jsonl.zst`) and need the `zstd` executable. Subagent
    threads are read only to be counted as agent traffic.
    """

    name = "codex"
    _head = re.compile(r'"type":"(session_meta|turn_context|response_item)"')
    _human_item_kinds = {"user.text"}

    def discover(self, home: Path) -> Iterable[Source]:
        root = home / ".codex"
        seen: set[str] = set()
        patterns = ("rollout-*.jsonl", "rollout-*.jsonl.zst")
        if not shutil.which("zstd"):
            patterns = patterns[:1]
        paths = [p for pattern in patterns for p in (root / "sessions").glob("**/" + pattern)]
        paths += [p for pattern in patterns for p in (root / "archived_sessions").glob(pattern)]
        for path in sorted(paths):
            key = path.name.removesuffix(".zst")  # an archived copy keeps the file name
            if key not in seen:
                seen.add(key)
                yield Source(self.name, path)

    def excluded(self, home: Path) -> dict[str, int]:
        if shutil.which("zstd"):
            return {}
        root = home / ".codex"
        count = sum(1 for _ in (root / "sessions").glob("**/rollout-*.jsonl.zst"))
        count += sum(1 for _ in (root / "archived_sessions").glob("rollout-*.jsonl.zst"))
        return {"compressed transcripts (install zstd to read them)": count}

    def _rows(self, path: Path) -> Iterator[dict]:
        with open_text(path) as handle:
            for line in handle:
                head = self._head.search(line[:200])
                if not head or len(line) > MAX_LINE:
                    continue
                if head.group(1) == "response_item" and '"type":"message"' not in line[:260]:
                    continue
                try:
                    value = json.loads(line)
                except ValueError:
                    continue
                if isinstance(value, dict) and isinstance(value.get("payload"), dict):
                    yield value

    def parse(self, source: Source) -> Iterator[Record]:
        turns = _Turns()
        session_id = source.path.name.split(".jsonl")[0]
        project = model = ""
        subagent = False
        seen_ids: set[str] = set()
        for row in self._rows(source.path):
            payload = row["payload"]
            row_type = row.get("type")
            if row_type == "session_meta":
                session_id = str(payload.get("id") or payload.get("session_id") or session_id)
                project = str(payload.get("cwd") or project)
                subagent = (
                    payload.get("thread_source") == "subagent"
                    or isinstance(payload.get("source"), dict)
                    or bool(payload.get("parent_thread_id"))
                )
                continue
            if row_type == "turn_context":
                model = str(payload.get("model") or model)
                project = project or str(payload.get("cwd") or "")
                continue
            role = payload.get("role")
            if role not in ("user", "assistant"):
                continue
            item_id = str(payload.get("id") or "")
            if item_id:
                if item_id in seen_ids:  # replayed history after a resume or fork
                    continue
                seen_ids.add(item_id)
            base = dict(
                harness=self.name,
                session_id=session_id,
                project=project,
                timestamp=str(row.get("timestamp") or ""),
            )
            content = payload.get("content")
            if role == "assistant":
                text = _text_blocks(content, ("output_text", "text"))
                if text.strip():
                    yield Record(
                        **base,
                        turn_index=turns.of(ASSISTANT),
                        role="assistant",
                        kind=ASSISTANT,
                        text=text[:MAX_TEXT],
                        model=model,
                    )
                continue
            kind, text = self._user_kind(payload, content, subagent)
            yield Record(**base, turn_index=turns.of(kind), role="user", kind=kind, text=text)

    def _user_kind(self, payload: dict, content: object, subagent: bool) -> tuple[str, str]:
        if subagent:
            return AGENT, ""
        blocks = [b for b in content if isinstance(b, dict)] if isinstance(content, list) else []
        meta = payload.get("internal_chat_message_metadata_passthrough")
        kinds = meta.get("content_item_kinds") if isinstance(meta, dict) else None
        if isinstance(kinds, list) and len(kinds) == len(blocks):
            if any(str(k).startswith("user.heartbeat") for k in kinds):
                return AUTOMATED, ""
            blocks = [b for b, k in zip(blocks, kinds) if k in self._human_item_kinds]
            if not blocks:
                return INJECTED, ""
        text = "\n".join(
            str(b.get("text", "")) for b in blocks if b.get("type") in ("input_text", "text")
        )
        return classify_user_text(text)


class Grok(Adapter):
    """`<home>/.grok/sessions/<url-encoded cwd>/<session id>/chat_history.jsonl`.

    Messages carry no timestamp; turn times come from the sibling
    `events.jsonl`, falling back to the session's creation time.
    """

    name = "grok"

    def discover(self, home: Path) -> Iterable[Source]:
        for path in sorted((home / ".grok" / "sessions").glob("*/*/chat_history.jsonl")):
            yield Source(self.name, path)

    @staticmethod
    def _json(path: Path) -> dict:
        try:
            value = json.loads(path.read_text(encoding="utf-8", errors="replace"))
        except (OSError, ValueError):
            return {}
        return value if isinstance(value, dict) else {}

    def parse(self, source: Source) -> Iterator[Record]:
        folder = source.path.parent
        summary = self._json(folder / "summary.json")
        context = self._json(folder / "prompt_context.json")
        headless = bool(context.get("is_non_interactive"))
        project = unquote(folder.parent.name)
        created = str(summary.get("created_at") or "")
        model = str(summary.get("current_model_id") or "")
        turn_times = [
            str(row.get("ts") or "")
            for row in _lines(folder / "events.jsonl")
            if row.get("type") == "turn_started"
        ]
        turns = _Turns()
        prompts = 0
        for row in _lines(source.path):
            row_type = row.get("type")
            if row_type not in ("user", "assistant"):
                continue
            timestamp = turn_times[prompts - 1] if 0 < prompts <= len(turn_times) else created
            base = dict(harness=self.name, session_id=folder.name, project=project)
            if row_type == "assistant":
                text = _text_blocks(row.get("content"))
                model = str(row.get("model_id") or model)
                if text.strip():
                    yield Record(
                        **base,
                        timestamp=timestamp,
                        turn_index=turns.of(ASSISTANT),
                        role="assistant",
                        kind=ASSISTANT,
                        text=text[:MAX_TEXT],
                        model=model,
                    )
                continue
            if "synthetic_reason" in row:
                kind, text = INJECTED, ""
            else:
                kind, text = classify_user_text(_text_blocks(row.get("content")))
                if kind == HUMAN:
                    prompts += 1
                    if headless:
                        kind, text = AGENT, ""  # a non-interactive run is driven by a program
            timestamp = turn_times[prompts - 1] if 0 < prompts <= len(turn_times) else created
            yield Record(
                **base, timestamp=timestamp, turn_index=turns.of(kind), role="user", kind=kind, text=text
            )


class Cursor(Adapter):
    """`<home>/.cursor/projects/<encoded cwd>/agent-transcripts/<id>/<id>.jsonl`.

    Minimal: these transcripts carry neither timestamps nor a model name.
    """

    name = "cursor"

    def discover(self, home: Path) -> Iterable[Source]:
        root = home / ".cursor" / "projects"
        for path in sorted(root.glob("*/agent-transcripts/*/*.jsonl")):
            yield Source(self.name, path)

    def parse(self, source: Source) -> Iterator[Record]:
        turns = _Turns()
        project = source.path.parents[2].name
        for row in _lines(source.path):
            role = row.get("role")
            if role not in ("user", "assistant"):
                continue
            message = row.get("message") if isinstance(row.get("message"), dict) else {}
            text = _text_blocks(message.get("content"))
            kind, text = (ASSISTANT, text[:MAX_TEXT]) if role == "assistant" else classify_user_text(text)
            if role == "assistant" and not text.strip():
                continue
            yield Record(
                harness=self.name,
                session_id=source.path.stem,
                project=project,
                timestamp="",
                turn_index=turns.of(kind),
                role=role,
                kind=kind,
                text=text,
            )


